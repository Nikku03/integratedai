"""Generate docs/BENCHMARKS.md and docs/COST_STORAGE.md from the JSON outputs in
eval_out/. Every number is read from a file produced by a run; nothing is typed in."""

from __future__ import annotations

import json
from pathlib import Path

from cie.agents.providers import PRICES, estimate_cost

TARGETS = {
    "exact_field_accuracy": ("Exact structured-field accuracy", 0.99),
    "citation_correctness": ("Citation correctness", 1.00),
    "recall@20": ("Retrieval recall@20", 0.90),
}


def _load(p: Path):
    return json.loads(p.read_text()) if p.exists() else None


def benchmarks_md(out: Path, docs: Path) -> str:
    bench = _load(out / "bench" / "bench_retrieval.json")
    glyph = (out / "bench" / "bench_glyph.md").read_text() if (out / "bench" / "bench_glyph.md").exists() else ""
    graph = (out / "bench" / "bench_graph.md").read_text() if (out / "bench" / "bench_graph.md").exists() else ""
    sim = (out / "simulation" / "simulation.md").read_text() if (out / "simulation" / "simulation.md").exists() else ""
    slow = (out / "slow_300_page.log").read_text() if (out / "slow_300_page.log").exists() else ""
    lines = ["# Benchmarks and acceptance results", "",
             "All numbers below were produced by `cie bench`, `cie simulate` and `pytest -m slow` in this build "
             "environment (4 vCPU, no GPU, PostgreSQL 16 + pgvector, `BAAI/bge-small-en-v1.5` via fastembed on CPU, Tesseract 5). "
             "They are regenerated by `python -m cie.eval.report`. Misses are reported as misses.", ""]
    if bench:
        main = bench["arms"]["hybrid+graph(bounded, REM)"]
        lines += ["## Acceptance targets (brief §13) on the synthetic evaluation set", "",
                  "| target | required | measured (hybrid + bounded graph) | met |", "|---|---|---|---|"]
        for key, (label, req) in TARGETS.items():
            val = main.get(key)
            lines.append(f"| {label} | ≥ {req:.0%} | {val:.1%} | {'yes' if val is not None and val >= req else '**no**'} |")
        lines.append(f"| Warm metadata lookup p95 | < 100 ms | {bench['warm_metadata_lookup_ms']['p95']} ms | {'yes' if bench['warm_metadata_lookup_ms']['p95'] < 100 else '**no**'} |")
        lines.append(f"| Full retrieval + rerank p95 | < 2000 ms | {main['latency_ms_p95']} ms | {'yes' if main['latency_ms_p95'] < 2000 else '**no**'} |")
        lines.append(f"| Unauthorized results in access-control questions | 0 | {main['permission_leaks']} | {'yes' if main['permission_leaks'] == 0 else '**no**'} |")
        lines.append(f"| Insufficient-evidence questions answered as such | all | {main['insufficient_evidence_detection']:.0%} | {'yes' if main['insufficient_evidence_detection'] == 1 else '**no**'} |")
        lines.append(f"| Planted cross-document conflict reported as conflict | all | {main['conflict_detection']:.0%} | {'yes' if main['conflict_detection'] == 1 else '**no**'} |")
        lines += ["", "### Caveats that matter more than the table", "",
                  f"* **In-sample.** The {bench['questions']} questions were used while the retrieval scoring was being fixed; every failure they exposed "
                  "was corrected until they passed. They demonstrate the mechanisms work, not generalisation. An out-of-sample set is the first roadmap item for evaluation.",
                  f"* **Small corpus.** {bench['docs']} documents, {bench['storage']['counts']['pages']} pages. On a corpus this size an evidence packet "
                  f"(~{bench['arms']['hybrid+graph(bounded, REM)']['packet_tokens_avg']:.0f} tokens) is not smaller than the whole corpus a principal can read; the packet only pays off at scale.",
                  "* **Graph expansion shows no gain here.** Hybrid, hybrid+graph and the bounded REM arm score identically because the questions rarely need "
                  "graph neighbours that lexical/vector search misses; the synthetic graph benchmark below shows where bounded expansion does help.",
                  "* **Extractive answers only.** No LLM was available; assisted mode and LLM agent strategies are untested against a live model.", ""]
        lines += ["Unsupported factual claims in strict mode: 0 by construction (every sentence of an extractive answer is a "
                  "record summary or a quote of a record's text with a citation); the assisted mode's claim verifier was tested with a fake provider only.", "",
                  "### Retrieval arms", "",
                  f"{bench['docs']} documents (contracts in three versions, a noisy scanned contract, a prompt-injected contract, a finance memo with a table, "
                  f"a restricted HR memo, an engineering requirements file, filler contracts with near-identical titles), {bench['questions']} questions.", "",
                  "| arm | recall@20 | exact-field acc | citation correctness | status acc | insufficient-evidence det. | conflict det. | permission leaks | p50 ms | p95 ms | packet tokens |",
                  "|---|---|---|---|---|---|---|---|---|---|---|"]
        for arm, v in bench["arms"].items():
            lines.append(f"| {arm} | {v['recall@20']} | {v['exact_field_accuracy']} (n={v['exact_n']}) | {v['citation_correctness']} (n={v['citations_checked']}) | "
                         f"{v['status_accuracy']} | {v['insufficient_evidence_detection']} | {v['conflict_detection']} | {v['permission_leaks']} | {v['latency_ms_p50']} | {v['latency_ms_p95']} | {v['packet_tokens_avg']} |")
        fc = bench["full-context"]
        lines += ["", "**Full-context prompting** (not run: no model available; this is what a model would have to hold per question):", ""]
        for pname, v in fc.items():
            if isinstance(v, dict):
                lines.append(f"- {pname}: ~{v['tokens_per_question']:,} tokens per question; est. ${v['est_cost_per_question_usd(claude-sonnet-5)']:.4f} per question at claude-sonnet-5 list prices "
                             f"vs {bench['arms']['hybrid+graph(bounded, REM)']['packet_tokens_avg']:.0f} packet tokens for the hybrid arm")
        lines += ["", "### Remaining failures (hybrid + bounded graph)", ""]
        for q in bench["per_question"]["hybrid+graph(bounded, REM)"]:
            if not q["correct"]:
                lines.append(f"- `{q['qid']}` ({q['kind']}): expected {q['expected']}, got {q['got']} — {q['answer'][:140]}")
            for b in q.get("bad_citations", []):
                lines.append(f"- `{q['qid']}` citation not verifiable on the cited page: {b['type']} p.{b['page_no']} quote `{b['quote'][:60]}`")
        if all(q["correct"] and not q.get("bad_citations") for q in bench["per_question"]["hybrid+graph(bounded, REM)"]):
            lines.append("- none")
    if slow:
        import re

        m = re.search(r"(\d+) passed.*?in ([\d.]+s|\d+:\d+:\d+)", slow)
        status = "passed" if (m and "failed" not in slow.split("short test summary")[-1]) else "FAILED"
        lines += ["", "## 300-page scanned contract (acceptance test 1)", "",
                  f"`pytest -m slow -k 300_page`: **{status}**. " + (f"Wall time {m.group(2)} including rasterisation at 110 dpi and Tesseract OCR of 300 pages; " if m else "")
                  + "all 300 pages stored with per-page confidence, completeness check passed, and the question about clause 177 was answered with a citation to page 177."]
    lines += scale_section(out)
    lines += ["", "## Glyph encoding benchmark", "", glyph, "", "## Graph topology benchmark (Ramanujan/expander vs sparse justified graph)", "", graph, "",
              "## Multi-agent simulation", "", sim]
    text = "\n".join(lines)
    (docs / "BENCHMARKS.md").write_text(text)
    return text


def scale_section(out: Path) -> list[str]:
    """Memory bank + retrieval at 10k / 100k / 1M records (``python -m cie.eval.bench_scale``),
    with the 1M row re-measured after the fixes it forced. Numbers come from the JSON only."""
    rep = _load(out / "scale" / "bench_scale.json")
    md_path = out / "scale" / "bench_scale.md"
    if not rep or not md_path.exists():
        return []
    sizes = rep["sizes"]
    loaded = [k for k, v in sizes.items() if v.get("index_build_seconds")]
    if not loaded:
        return []
    big = max(loaded, key=lambda k: int(k))
    after = next((k for k in sizes if k.startswith(big) and k != big), None)
    b = sizes[big]
    hb = b["admin@company"]["hybrid+graph(bounded)"]
    lines = ["", "## Scale benchmark: memory bank and retrieval at 10k, 100k and 1M records", "",
             "`python -m cie.eval.bench_scale` loads a synthetic tenant of N typed records (12 per document: fees, penalties, notice periods, "
             "terms, liability caps, decisions, parties, signatories, open questions, notes), N/4 sections and about 1.35 edges per record through "
             "binary COPY, builds the indexes, then runs 60 templated questions (50 with a known target document and record type, 10 unanswerable) "
             "through the full retrieval pipeline as an admin over the whole company and as an analyst confined to one department (20% of the data). "
             "`hit@20` is whether the target document's record of the expected type is in the top 20 of the packet; it measures retrieval, not answer wording. "
             "Cold = first pass after the load, warm = second pass. Hardware as above (4 vCPU, no GPU, embeddings on CPU).", "",
             md_path.read_text().strip(), ""]
    st = b["storage"]
    lines += [f"**At {int(big):,} records** ({b['load']['n_sections']:,} sections, {b['load']['n_documents']:,} documents): load {b['load']['copy_seconds']} s, "
              f"tsvectors {b['load']['tsvector_seconds']} s, HNSW build on records {b['index_build_seconds']['ix_records_embedding_hnsw']} s, all indexes "
              f"{b['index_build_total_seconds']} s; the records table takes {st['memory_records']['total_bytes'] / 1e9:.1f} GB with indexes "
              f"({st['ix_records_embedding_hnsw_bytes'] / 1e9:.1f} GB HNSW, {st['ix_records_tsv_bytes'] / 1e6:.0f} MB GIN), sections {st['sections']['total_bytes'] / 1e9:.1f} GB, "
              f"edges {st['record_links']['total_bytes'] / 1e6:.0f} MB. Warm metadata lookup p95 {b['warm_metadata_lookup_ms']['p95']} ms.", ""]
    if after:
        a = sizes[after]
        ha = a["admin@company"]["hybrid+graph(bounded)"]
        la = a["admin@company"].get("lexical-only", {})
        lb = b["admin@company"].get("lexical-only", {})
        lines += [f"**The first {int(big):,}-record run failed the latency target and most questions** (hybrid warm p50 {hb['warm_p50_ms']} ms, p95 {hb['warm_p95_ms']} ms, "
                  f"hit@20 {hb['hit_at_20']}). The stage timings named the causes, all in the retrieval code rather than in PostgreSQL: a `COUNT(*)` per query to size the "
                  f"graph budget, an unbounded OR full-text tier that ranked every row sharing a common word, a trigram similarity fallback over every entity summary, "
                  f"a document-name search that concatenated two indexed columns (so neither trigram index applied) and dropped the numeral that told namesakes apart, "
                  f"and candidate lists cut at ties. After the fixes (row estimate from `pg_class`; four lexical tiers with an entity-anchored tier and a partial-match tier "
                  f"restricted to lexemes the planner statistics show are rare, bounded by a statement timeout; per-column trigram search with whole-word numerals and "
                  f"best-match-only documents; bounded trigram fallback; embeddings and tsvectors never read back) the same tenant re-measured at hybrid warm p50 "
                  f"{ha['warm_p50_ms']} ms, p95 {ha['warm_p95_ms']} ms, hit@20 {ha['hit_at_20']} (lexical stage p50 {lb.get('stage_ms_p50', {}).get('lexical_ms', '?')} → "
                  f"{ha['stage_ms_p50'].get('lexical_ms', '?')} ms; lexical-only hit@20 {lb.get('hit_at_20', '?')} → {la.get('hit_at_20', '?')}). "
                  f"The 10k and 100k rows are from the first run and were not re-measured; their latencies are upper bounds for the fixed code.", ""]
    lines += ["### What this does and does not show", "",
              "* **Synthetic and templated.** Every record carries its supplier's name and the questions name the supplier, which is friendlier to entity-anchored "
              "lexical search than real documents, where a fee clause rarely repeats the supplier's name (the in-sample corpus above covers that case). "
              "Vector-only hit@20 is low because the 384-d model cannot tell 50,000 near-identical contracts apart; that is a property of templated data as much as of the model.",
              "* **Names that are prefixes of other names stay ambiguous.** \"Alpine Cloud\" matches every \"Alpine Cloud N\" supplier equally; the exact-name document "
              "ties with its namesakes and can fall outside the top 20. This is the remaining systematic miss.",
              "* **\"vector-only\" still narrows to the named documents.** That arm disables the exact, lexical and graph stages, but the document-name search "
              "(trigram index on titles and filenames) still restricts one of its candidate lists to the documents the question names; its rise between the two 1M rows "
              "is the document-name fix, not the embedding model.",
              "* **Timeouts are reported, not hidden.** A bounded tier that times out returns nothing for that tier; the `timeouts` column counts questions whose whole retrieval "
              "exceeded the 60 s statement timeout (cold cache after a database restart).",
              "* **One machine, one tenant, no concurrency.** Latencies are single-client; throughput under concurrent load was not measured. The re-measured 1M row "
              "shared the machine with a three-minute run of the test suite, so its cold p95 is, if anything, pessimistic.", ""]
    return lines


def cost_storage_md(out: Path, docs: Path) -> str:
    bench = _load(out / "bench" / "bench_retrieval.json")
    sim = _load(out / "simulation" / "simulation.json")
    lines = ["# Cost and storage report", "",
             "Measured on the synthetic evaluation corpus in this build; projections are arithmetic on the measured per-unit numbers and say so.", ""]
    if bench:
        st = bench["storage"]
        counts = st["counts"]
        raw = st["raw_bytes"]
        tb = st["table_bytes_total_db"]
        lines += ["## Measured storage", "",
                  "| quantity | value |", "|---|---|",
                  f"| documents / pages / sections / records | {counts['documents']} / {counts['pages']} / {counts['sections']} / {counts['records']} |",
                  f"| raw vault bytes (deduplicated blobs) | {raw:,} ({raw / 1e6:.1f} MB) |",
                  f"| raw bytes per page | {raw / max(counts['pages'], 1):,.0f} |"]
        pr = st.get("bytes_per_row", {})
        for t in tb:
            lines.append(f"| `{t}` table incl. indexes, bytes per row (database-wide) | {pr.get(t) or 'n/a'} |")
        per_rec = pr.get("memory_records") or tb["memory_records"] / max(1, counts["records"])
        per_sec = pr.get("sections") or tb["sections"] / max(1, counts["sections"])
        lines += ["", f"A memory record costs about {per_rec:,.0f} bytes on disk and a section about {per_sec:,.0f} bytes, indexes included "
                  "(384-d float32 embedding = 1,536 bytes each, HNSW and GIN index entries, tsvector, JSONB glyph and provenance). "
                  "Evidence packets are the largest growing table because every search stores its full packet for reproducibility; they can be "
                  "expired by retention policy.", "",
                  "## Projection to a 200-million-token project memory", "",
                  "Assuming ~350 tokens per section and ~120 tokens per record (measured averages on this corpus are of that order), 200M addressable tokens ≈ "
                  "450k sections + 350k records:", "",
                  "| component | estimate |", "|---|---|",
                  f"| sections (450k × {per_sec:,.0f} B) | {450_000 * per_sec / 1e9:.1f} GB |",
                  f"| records (350k × {per_rec:,.0f} B) | {350_000 * per_rec / 1e9:.1f} GB |",
                  f"| raw vault (450k sections ≈ 60k pages × {raw / max(counts['pages'], 1):,.0f} B/page measured on PDFs with embedded fonts) | {60_000 * raw / max(counts['pages'], 1) / 1e9:.1f} GB |",
                  "", "This fits one PostgreSQL instance with room; HNSW build time and index memory, not disk, are the first limits (see ROADMAP.md)."]
        scale = _load(out / "scale" / "bench_scale.json")
        big = max((k for k, v in (scale or {}).get("sizes", {}).items() if v.get("index_build_seconds")), key=lambda k: int(k), default=None)
        if big:
            b = scale["sizes"][big]
            st, ld = b["storage"], b["load"]
            lines += ["", f"## Measured at {int(big):,} synthetic records", "",
                      "| quantity | value |", "|---|---|",
                      f"| records / sections / documents | {ld['n_records']:,} / {ld['n_sections']:,} / {ld['n_documents']:,} |",
                      f"| `memory_records` table incl. indexes | {st['memory_records']['total_bytes'] / 1e9:.2f} GB ({st['memory_records']['total_bytes'] / ld['n_records']:,.0f} B per record) |",
                      f"| of which HNSW index / GIN tsvector index | {st['ix_records_embedding_hnsw_bytes'] / 1e9:.2f} GB / {st['ix_records_tsv_bytes'] / 1e6:.0f} MB |",
                      f"| `sections` table incl. indexes | {st['sections']['total_bytes'] / 1e9:.2f} GB ({st['sections']['total_bytes'] / ld['n_sections']:,.0f} B per section) |",
                      f"| `record_links` table incl. indexes | {st['record_links']['total_bytes'] / 1e6:.0f} MB |",
                      f"| load (binary COPY) / tsvectors / HNSW on records / all indexes | {ld['copy_seconds']} s / {ld['tsvector_seconds']} s / "
                      f"{b['index_build_seconds']['ix_records_embedding_hnsw']} s / {b['index_build_total_seconds']} s |", "",
                      "Synthetic records are shorter than extracted ones (no page-level provenance, small glyphs), so the per-row figure is a floor; the "
                      "per-row figure from the extracted corpus above is the better estimate for real documents. Retrieval latency at this size is in BENCHMARKS.md."]
        main = bench["arms"]["hybrid+graph(bounded, REM)"]
        fc = bench["full-context"]
        adm = fc.get("admin", {})
        lines += ["", "## Tokens and model cost per question", "",
                  "| approach | tokens sent to the model per question | est. cost at claude-sonnet-5 list price |", "|---|---|---|",
                  f"| full context (everything the admin can read) | ~{adm.get('tokens_per_question', 0):,} | ${adm.get('est_cost_per_question_usd(claude-sonnet-5)', 0):.4f} |",
                  f"| hybrid evidence packet (this system, assisted mode) | ~{main['packet_tokens_avg']:,.0f} | ${estimate_cost('claude-sonnet-5', int(main['packet_tokens_avg']), 300):.4f} |",
                  "| strict extractive mode (this system, default) | 0 | $0 |", "",
                  "The corpus is small, so full context is still cheap in absolute terms; the ratio is what scales. At 200M tokens the full-context approach is impossible "
                  "(no model holds it) while the packet stays at a few thousand tokens.", "",
                  "## Latency and compute", "",
                  f"Retrieval + rerank p50/p95: {main['latency_ms_p50']} / {main['latency_ms_p95']} ms on CPU with the embedding model warm; warm metadata lookup p95 "
                  f"{bench['warm_metadata_lookup_ms']['p95']} ms. Ingestion of the corpus took {bench['ingest_seconds']} s including OCR of the scanned document "
                  "(Tesseract ≈ 0.5 s per page at 110–150 dpi on one core)."]
    if sim:
        lines += ["", "## Multi-agent run", "", "| agent | tasks | tokens in | tokens out | cost USD |", "|---|---|---|---|---|"]
        for a, v in sim["per_agent"].items():
            lines.append(f"| {a} | {v['tasks']} | {v['tokens_in']:,} | {v['tokens_out']:,} | {v['cost_usd']:.4f} |")
        lines += ["", f"Strategy `{sim['strategy']}` (no model calls, so cost is 0); token figures are the estimated size of each agent's brief + evidence packet, "
                  "i.e. what an LLM strategy would have been sent. Messages carried "
                  f"{sum(m['tokens'] for m in sim['messages']):,} tokens in total across {sum(m['count'] for m in sim['messages'])} structured messages."]
    lines += ["", "## Price table used for estimates", "", "| model | $/M input | $/M output |", "|---|---|---|"]
    for m, (i, o) in PRICES.items():
        lines.append(f"| {m} | {i} | {o} |")
    lines += ["", "Prices are list prices typed into `cie.agents.providers.PRICES`; real spend comes from provider usage reports, which this build could not collect."]
    text = "\n".join(lines)
    (docs / "COST_STORAGE.md").write_text(text)
    return text


def main(out: Path = Path("eval_out"), docs: Path = Path("docs")) -> None:
    benchmarks_md(out, docs)
    cost_storage_md(out, docs)
    print("wrote", docs / "BENCHMARKS.md", docs / "COST_STORAGE.md")


if __name__ == "__main__":  # pragma: no cover
    main()
